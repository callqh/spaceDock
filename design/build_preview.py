"""Generate CSS and color checks from tokens.json. No third-party dependencies."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT / 'tokens.json').read_text())

def declarations(mode):
    values = {**data['color'][mode], **{'material-' + key: value for key, value in data['material'][mode].items()}}
    return '\n'.join(f'  --{key}: {value};' for key, value in values.items())

css = [':root {', declarations('light'), f'  --material-blur: {data["material"]["blur"]}px;', f'  --material-saturation: {data["material"]["saturation"]};', f'  --key-bottom-border: {data["material"]["keyBottomBorder"]}px;']
for group in ('space', 'radius', 'size', 'stroke', 'component'):
    css += [f'  --{group}-{key}: {value}px;' for key, value in data[group].items()]
for name, style in data['typography']['styles'].items():
    for key, value in style.items():
        css.append(f'  --type-{name}-{key}: {value}{"" if key == "weight" else "px"};')
for key in ('fast', 'normal', 'instant'):
    css.append(f'  --motion-{key}: {data["motion"][key]}ms;')
css += ['}', '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) {', declarations('dark'), '} }', ':root[data-theme="dark"] {', declarations('dark'), '}']
for mode, shadow in data['shadow'].items():
    css.append(f':root[data-theme="{mode}"] {{ --panel-shadow: {shadow["x"]}px {shadow["y"]}px {shadow["blur"]}px rgb(0 0 0 / {shadow["opacity"]}); }}')
css.append(':root { --panel-shadow: 0 8px 24px rgb(0 0 0 / .12); }')
(ROOT / 'tokens.css').write_text('/* Generated by build_preview.py; edit tokens.json. */\n' + '\n'.join(css) + '\n')

def luminance(color):
    channels = [int(color[i:i+2], 16) / 255 for i in (1, 3, 5)]
    channels = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in channels]
    return sum(c * w for c, w in zip(channels, (.2126, .7152, .0722)))

rows = []
for mode, colors in data['color'].items():
    for fg, bg in [('textPrimary', 'surface'), ('textSecondary', 'surface'), ('textSecondary', 'canvas'), ('onAccent', 'accent'), ('accent', 'accentSubtle'), ('success', 'successSubtle'), ('warning', 'warningSubtle'), ('danger', 'dangerSubtle'), ('controlBorder', 'surface'), ('focus', 'surface'), ('sparkInk', 'spark')]:
        low, high = sorted([luminance(colors[fg]), luminance(colors[bg])])
        ratio = (high + .05) / (low + .05)
        limit = 3 if fg in ('controlBorder', 'focus') else 4.5
        assert ratio >= limit, (mode, fg, bg, ratio)
        rows.append(f'| {mode} | {fg} / {bg} | {ratio:.2f}:1 |')
(ROOT / 'contrast-check.md').write_text('# v0.5 固定色对检查\n\n2026-11-06。由 build_preview.py 根据 tokens.json 计算 sRGB 相对亮度。正文目标 4.5:1，必要边界与焦点目标 3:1。禁用文字与装饰分隔线不承担上述角色；此检查仅覆盖不透明回退色，不证明任意背景上的玻璃材质对比度，也不等于完整无障碍验收。\n\n| 模式 | 色对 | 比值 |\n|---|---|---|\n' + '\n'.join(rows) + '\n')
print('Generated tokens.css; 22 color pairs passed.')
